"""
Sensor noise injection for the validation pipeline.

============================= HONEST SCOPE =================================
This module adds configurable Gaussian noise + fixed bias + linear drift
to a reference trajectory to produce a simulated "noisy estimate" -- the
abstract's "controlled camera and IMU noise, bias, drift, and
measurement uncertainty... to reproduce realistic sensing conditions."

The noise MAGNITUDES below (std/bias/drift values) are illustrative
defaults, not measured characteristics of any real camera or IMU. They
exist so the validation pipeline (motion_generator -> noise_model ->
trajectory_metrics) can be exercised end-to-end today. Before this
pipeline is used to make any real accuracy claim, these presets must be
replaced with error characteristics measured from the ACTUAL camera
pipeline (src/pose + src/features -- e.g. by comparing FPPA/flexion
output against a known controlled motion) and the actual IMU hardware
once purchased (per src/sensors/imu_fusion.py's calibration
requirements). Running this with illustrative defaults and reporting the
resulting RMSE as "DriftGuard's accuracy" would be circular -- it would
only measure how well the metrics code recovers noise it itself added.
==============================================================================
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

ROTATIONAL_COLUMNS = ("flexion_extension_deg", "abduction_adduction_deg", "internal_external_rotation_deg")
TRANSLATIONAL_COLUMNS = ("ap_translation_mm", "ml_translation_mm", "si_translation_mm")


@dataclass
class NoiseProfile:
    name: str
    rotational_std_deg: float
    rotational_bias_deg: float
    rotational_drift_deg_per_s: float
    translational_std_mm: float
    translational_bias_mm: float
    translational_drift_mm_per_s: float


# Illustrative presets only -- see module docstring. "camera" is modeled
# as having larger translational uncertainty (depth from a single RGB
# view is the weakest link) and lower rotational noise; "imu" is modeled
# as having very low noise but a meaningful drift term (the well-known
# IMU integration-drift problem motivating the project's camera+IMU
# fusion design, itself not yet implemented -- see imu_fusion.py).
NOISE_PRESETS = {
    "camera": NoiseProfile(
        name="camera",
        rotational_std_deg=1.5,
        rotational_bias_deg=0.5,
        rotational_drift_deg_per_s=0.0,
        translational_std_mm=3.0,
        translational_bias_mm=1.0,
        translational_drift_mm_per_s=0.0,
    ),
    "imu": NoiseProfile(
        name="imu",
        rotational_std_deg=0.3,
        rotational_bias_deg=0.2,
        rotational_drift_deg_per_s=0.5,
        translational_std_mm=0.5,
        translational_bias_mm=0.2,
        translational_drift_mm_per_s=2.0,
    ),
    "fused": NoiseProfile(
        # A simple, illustrative STAND-IN for what camera+IMU fusion
        # (src/sensors/imu_fusion.py, not yet implemented for real)
        # would ideally achieve: better than either sensor alone. This
        # is NOT a claim that fusion achieves this automatically --
        # real fusion performance depends entirely on the real EKF
        # tuning described (and deferred) in imu_fusion.py.
        name="fused",
        rotational_std_deg=0.8,
        rotational_bias_deg=0.2,
        rotational_drift_deg_per_s=0.05,
        translational_std_mm=1.5,
        translational_bias_mm=0.3,
        translational_drift_mm_per_s=0.2,
    ),
}


def inject_noise(reference_df: pd.DataFrame, profile: NoiseProfile, random_state: int | None = 42) -> pd.DataFrame:
    """
    Produce a noisy "estimate" trajectory from a reference trajectory
    (as generated by motion_generator.generate_reference_trajectory),
    simulating: bias (constant offset), Gaussian noise (per-sample), and
    linear drift (grows with elapsed time).
    """
    rng = np.random.default_rng(random_state)
    noisy = reference_df.copy()
    t = reference_df["time_s"].to_numpy()

    for col in ROTATIONAL_COLUMNS:
        noise = rng.normal(0, profile.rotational_std_deg, size=len(t))
        drift = profile.rotational_drift_deg_per_s * t
        noisy[col] = reference_df[col] + profile.rotational_bias_deg + noise + drift

    for col in TRANSLATIONAL_COLUMNS:
        noise = rng.normal(0, profile.translational_std_mm, size=len(t))
        drift = profile.translational_drift_mm_per_s * t
        noisy[col] = reference_df[col] + profile.translational_bias_mm + noise + drift

    return noisy
