"""
Multi-Athlete Clinician-Readable Report Generator
===================================================
Produces a structured JSON report suitable for display to clinicians or for
PDF generation. This module:

  - Calls assess_session_quality() to attach quality indicators to each athlete
  - Summarises biomechanical findings per athlete (only from valid frames)
  - Attaches explicit provenance: measurement source, algorithm version, caveats
  - Includes a mandatory screening disclaimer (never diagnosis / injury probability)
  - Returns a plain dict — no DB writes, no side effects

Invariants
----------
- Does not modify any existing module or DB schema.
- No MediaPipe / CV2 imports — safe to call from any context.
- Never imputes or fabricates missing values; absent metrics appear as null.
- Parameters 19-22 (depth/stereo) always appear as "not_available".
"""

from __future__ import annotations

import platform
import sys
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from src.pose.multi_athlete_quality import (
    QUALITY_HIGH,
    QUALITY_ACCEPTABLE,
    QUALITY_LOW,
    QUALITY_INSUFFICIENT,
    assess_session_quality,
    AthleteQualityResult,
)

# Algorithm / provenance metadata
_ALGORITHM_VERSION = "2.0-multi-athlete"
_POSE_MODEL        = "mediapipe_pose_landmarker_full_v1"
_TRACKER           = "centroid_iou_with_uncertainty_heuristic"

# Mandatory clinical disclaimer — must appear in every report
SCREENING_DISCLAIMER = (
    "SCREENING OUTPUT ONLY — NOT A CLINICAL DIAGNOSIS. "
    "This report is generated by an automated pose-estimation and biomechanical "
    "analysis system. Scores and measurements are screening outputs intended to "
    "assist qualified clinicians; they do not constitute a clinical diagnosis, "
    "injury probability estimate, or medical advice. All findings must be reviewed "
    "by a licensed healthcare professional before any clinical decision is made. "
    "The system has not been validated for regulatory clearance as a medical device."
)

# Mapping for the 22-parameter set — params 19-22 are depth/stereo only
_PARAMS_UNAVAILABLE = {
    "param_19_knee_valgus_3d":      "not_available",
    "param_20_hip_adduction_3d":    "not_available",
    "param_21_trunk_lean_3d":       "not_available",
    "param_22_pelvic_drop_3d":      "not_available",
}


def _quality_summary(qr: AthleteQualityResult) -> Dict[str, Any]:
    return {
        "quality_tier":                qr.quality_tier,
        "quality_score":               qr.quality_score,
        "is_sufficient_for_screening": qr.is_sufficient_for_screening,
        "coverage_pct":                qr.coverage_pct,
        "uncertainty_pct":             qr.uncertainty_pct,
        "biomechanics_valid_pct":      qr.biomechanics_valid_pct,
        "caveats":                     qr.caveats,
    }


def _bio_entry(athlete: Dict[str, Any], quality: AthleteQualityResult) -> Dict[str, Any]:
    """Build the biomechanics block for one athlete."""
    # Only include values that exist and are not None
    def _val(key: str) -> Optional[float]:
        v = athlete.get(key)
        return round(float(v), 2) if v is not None else None

    bio: Dict[str, Any] = {
        # 2D pose-derived parameters (params 1-2 subset available)
        "avg_fppa_left":          _val("avg_fppa_left"),
        "avg_knee_flex_left":     _val("avg_knee_flex_left"),
        "peak_fppa_left":         _val("peak_fppa_left"),
        "peak_knee_flex_left":    _val("peak_knee_flex_left"),
        # Params 19-22 — depth/stereo input required
        **_PARAMS_UNAVAILABLE,
        # Measurement source
        "measurement_source":     "POSE_DERIVED",
        "measurement_status":     "ESTIMATED_PROXY",
        "validation_status":      "NOT_VALIDATED",
    }

    # If quality is INSUFFICIENT, add blanket caveat to each bio block
    if not quality.is_sufficient_for_screening:
        bio["_quality_warning"] = (
            f"Quality tier {quality.quality_tier}: biomechanical values "
            "may be unreliable — do not use for screening decisions."
        )

    return bio


def _provenance_block(result: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "algorithm_version":   _ALGORITHM_VERSION,
        "pose_model":          _POSE_MODEL,
        "tracker":             _TRACKER,
        "session_id":          result.get("session_id", ""),
        "source_video":        result.get("source_video", ""),
        "total_frames":        result.get("total_frames", 0),
        "fps":                 result.get("fps", 0.0),
        "duration_sec":        result.get("duration_sec", 0.0),
        "max_athletes_config": result.get("max_athletes", 5),
        "athletes_detected":   len(result.get("athletes", [])),
        "generated_at_utc":    datetime.now(timezone.utc).isoformat(),
        "python_version":      sys.version.split()[0],
        "platform":            platform.system(),
    }


def _risk_interpretation(qr: AthleteQualityResult, athlete: Dict[str, Any]) -> str:
    """
    Plain-language interpretation for a clinician — conservative, no fabrication.
    """
    if not qr.is_sufficient_for_screening:
        return (
            f"Data quality for {qr.display_name} is {qr.quality_tier}. "
            "The available frames are insufficient for a reliable screening "
            "interpretation. Collect additional footage or review manually."
        )

    fppa = athlete.get("avg_fppa_left")
    flex = athlete.get("avg_knee_flex_left")

    lines: List[str] = [f"Screening summary for {qr.display_name} (quality: {qr.quality_tier})."]

    if fppa is not None:
        direction = "valgus" if fppa < 0 else "varus"
        lines.append(
            f"Average FPPA (left): {fppa:.1f}° ({direction} bias). "
            "Elevated valgus angles (< -10°) may warrant further assessment."
        )
    else:
        lines.append("FPPA (left): insufficient data — not reported.")

    if flex is not None:
        lines.append(
            f"Average knee flexion (left): {flex:.1f}°. "
            "Values below 45° at landing may indicate reduced shock absorption."
        )
    else:
        lines.append("Knee flexion (left): insufficient data — not reported.")

    if qr.caveats:
        lines.append("Data caveats: " + "; ".join(qr.caveats))

    return " ".join(lines)


def generate_multi_athlete_report(result: Dict[str, Any]) -> Dict[str, Any]:
    """
    Build a clinician-readable report from a process_multi_athlete_video() result.

    Parameters
    ----------
    result : dict
        Return value of process_multi_athlete_video().

    Returns
    -------
    dict with keys:
        disclaimer, provenance, session_quality_summary,
        athletes (list of per-athlete report blocks)
    """
    quality_map = assess_session_quality(result)
    provenance  = _provenance_block(result)

    athlete_reports: List[Dict[str, Any]] = []
    any_sufficient = False

    for athlete in result.get("athletes", []):
        tid     = athlete["track_id"]
        quality = quality_map.get(tid)
        if quality is None:
            continue

        if quality.is_sufficient_for_screening:
            any_sufficient = True

        athlete_reports.append({
            "track_id":       tid,
            "display_name":   athlete.get("display_name", f"Athlete #{tid}"),
            "color":          athlete.get("color", "#FFFFFF"),
            "tracking": {
                "first_seen_s":   athlete.get("first_seen_s"),
                "last_seen_s":    athlete.get("last_seen_s"),
                "frames_tracked": athlete.get("frames_tracked"),
            },
            "quality":         _quality_summary(quality),
            "biomechanics":    _bio_entry(athlete, quality),
            "interpretation":  _risk_interpretation(quality, athlete),
        })

    # Session-level quality roll-up
    tiers = [quality_map[a["track_id"]].quality_tier
              for a in result.get("athletes", [])
              if a["track_id"] in quality_map]
    tier_counts = {t: tiers.count(t) for t in
                   [QUALITY_HIGH, QUALITY_ACCEPTABLE, QUALITY_LOW, QUALITY_INSUFFICIENT]}

    session_quality_summary = {
        "athletes_detected":          len(athlete_reports),
        "athletes_sufficient_for_screening": sum(
            1 for qr in quality_map.values() if qr.is_sufficient_for_screening
        ),
        "any_athlete_sufficient":     any_sufficient,
        "quality_tier_counts":        tier_counts,
        "session_recommendation": (
            "At least one athlete has sufficient data for screening review."
            if any_sufficient else
            "No athlete has sufficient data quality for reliable screening. "
            "Consider re-recording with better framing and lighting."
        ),
    }

    return {
        "disclaimer":              SCREENING_DISCLAIMER,
        "provenance":              provenance,
        "session_quality_summary": session_quality_summary,
        "athletes":                athlete_reports,
    }
