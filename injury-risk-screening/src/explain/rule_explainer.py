@dataclass
class EventExplanation:
    athlete_id: str
    feature_name: str
    feature_label: str
    event_value: float
    baseline_median: float
    baseline_iqr: float
    deviation_iqr: float
    band: RiskBand
    persisted: bool
    headline: str
    detail: str
    citation: str


def explain_event(
    athlete_id: str,
    feature_name: str,
    event_value: float,
    baseline_median: float,
    baseline_iqr: float,
    deviation_iqr: float,
    band: RiskBand,
    persisted: bool,
) -> EventExplanation:
    """Build a human-readable explanation enforcing screening terminology."""
    label = FEATURE_LABELS.get(feature_name, feature_name)
    citation = FEATURE_CITATIONS.get(feature_name, "")
    direction = "above" if event_value >= baseline_median else "below"
    abs_dev = abs(deviation_iqr) if deviation_iqr == deviation_iqr else float("nan")

    if band == RiskBand.LOW or not persisted:
        headline = f"{label.capitalize()} is within this athlete's normal range."
        detail = (
            f"This event's value ({event_value:.1f}) is close to the athlete's own "
            f"baseline median ({baseline_median:.1f}), well inside their typical "
            f"event-to-event variation."
            if not persisted or band == RiskBand.LOW
            else ""
        )
        if not persisted:
            detail += (
                " Note: not enough events have been recorded yet to confirm a "
                "trend -- this is a single-event reading, not a confirmed pattern."
            )
        return EventExplanation(
            athlete_id=athlete_id,
            feature_name=feature_name,
            feature_label=label,
            event_value=event_value,
            baseline_median=baseline_median,
            baseline_iqr=baseline_iqr,
            deviation_iqr=deviation_iqr,
            band=band,
            persisted=persisted,
            headline=headline,
            detail=detail.strip(),
            citation=citation,
        )

    band_word = "moderately elevated" if band == RiskBand.MODERATE else "substantially elevated"
    headline = f"Elevated movement-risk pattern: {label.capitalize()} has been {band_word} across recent sessions."
    detail = (
        f"This athlete's recent movement trials show a biomechanical deviation in {label}, consistently "
        f"{direction} their established baseline median of {baseline_median:.1f} "
        f"degrees (+/-{baseline_iqr / 2:.1f} degrees) by {abs_dev:.1f}x their normal spread. "
        f"This pattern has persisted across at least 3 of their last 5 recorded events."
    )
    return EventExplanation(
        athlete_id=athlete_id,
        feature_name=feature_name,
        feature_label=label,
        event_value=event_value,
        baseline_median=baseline_median,
        baseline_iqr=baseline_iqr,
        deviation_iqr=deviation_iqr,
        band=band,
        persisted=persisted,
        headline=headline,
        detail=detail,
        citation=citation,
    )


def explanation_to_dict(exp: EventExplanation) -> dict:
    return {
        "athlete_id": exp.athlete_id,
        "feature": exp.feature_name,
        "feature_label": exp.feature_label,
        "event_value": exp.event_value,
        "baseline_median": exp.baseline_median,
        "baseline_iqr": exp.baseline_iqr,
        "deviation_iqr": exp.deviation_iqr,
        "band": str(exp.band),
        "persisted": exp.persisted,
        "headline": exp.headline,
        "detail": exp.detail,
        "citation": exp.citation,
    }
