#!/usr/bin/env python3
"""
Thermal-monitoring sample demo -- runs the REAL ROI-extraction and
bilateral-asymmetry logic from src/sensors/thermal_capture.py against a
SYNTHETIC thermal frame (simulated Celsius values), so you can see what
the inflammation-flagging output looks like without owning a thermal
camera yet.

============================= HONEST SCOPE =================================
The numbers below are generated by this script, not measured by any real
sensor. This demonstrates:
  - that the ROI-extraction and asymmetry math is real, runs end-to-end,
    and is already wired for the moment real calibrated thermal frames
    exist
  - roughly what a notable vs. non-notable asymmetry reading would look
    like, using a baseline skin temperature (~31-33C, a commonly cited
    resting skin-surface range) plus an optional simulated "hotspot" to
    represent localized inflammation

It does NOT demonstrate that any specific thermal camera, once
purchased, will read these exact values on a real knee -- that depends
on the device's real calibration (see module docstring in
src/sensors/thermal_capture.py for exactly what calibration step is
still needed).
==============================================================================
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.sensors.thermal_capture import (
    ThermalFrame,
    compute_bilateral_asymmetry,
    extract_knee_roi_temperature,
)

FRAME_WIDTH = 160
FRAME_HEIGHT = 120
BASELINE_SKIN_TEMP_C = 32.0
LEFT_KNEE_PIXEL = (50, 60)
RIGHT_KNEE_PIXEL = (110, 60)


def build_synthetic_thermal_frame(hotspot_knee: str | None, hotspot_delta_c: float) -> ThermalFrame:
    """
    Builds a plausible-looking synthetic thermal frame: a uniform
    baseline skin temperature with mild smooth spatial variation (real
    skin is not perfectly uniform), and an optional elevated "hotspot"
    centered on one knee to simulate localized inflammation.
    """
    rng = np.random.default_rng(0)
    temp = np.full((FRAME_HEIGHT, FRAME_WIDTH), BASELINE_SKIN_TEMP_C, dtype=np.float64)
    temp += rng.normal(0, 0.15, size=temp.shape)  # mild sensor/skin noise

    if hotspot_knee is not None:
        center = LEFT_KNEE_PIXEL if hotspot_knee == "left" else RIGHT_KNEE_PIXEL
        yy, xx = np.mgrid[0:FRAME_HEIGHT, 0:FRAME_WIDTH]
        dist2 = (xx - center[0]) ** 2 + (yy - center[1]) ** 2
        gaussian_bump = hotspot_delta_c * np.exp(-dist2 / (2 * 12.0 ** 2))
        temp += gaussian_bump

    return ThermalFrame(temperature_c=temp, width=FRAME_WIDTH, height=FRAME_HEIGHT)


def run_demo(hotspot_knee: str | None, hotspot_delta_c: float) -> None:
    frame = build_synthetic_thermal_frame(hotspot_knee, hotspot_delta_c)

    left_temp = extract_knee_roi_temperature(frame, *LEFT_KNEE_PIXEL)
    right_temp = extract_knee_roi_temperature(frame, *RIGHT_KNEE_PIXEL)
    result = compute_bilateral_asymmetry(left_temp, right_temp)

    print("=" * 60)
    print("THERMAL MONITORING -- SAMPLE PROOF OF CONCEPT (SIMULATED DATA)")
    print("=" * 60)
    print(f"Simulated hotspot: {hotspot_knee or 'none'} (+{hotspot_delta_c:.1f}C)" if hotspot_knee else "Simulated hotspot: none (both knees at baseline)")
    print(f"Left knee ROI mean temp:  {result.left_temp_c:.2f} C")
    print(f"Right knee ROI mean temp: {result.right_temp_c:.2f} C")
    print(f"Bilateral asymmetry:      {result.asymmetry_c:.2f} C")
    print(f"Notable (>{0.5:.1f}C threshold)?  {'YES -- flag for clinician review' if result.notable else 'no'}")
    print()
    print("Reminder: this is simulated input data run through real extraction/")
    print("asymmetry logic. A real thermal camera plus its device-specific")
    print("calibration is still required before this reflects an actual patient.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--hotspot-knee", choices=["left", "right", "none"], default="right",
        help="Which knee (if any) gets a simulated inflammation hotspot (default: right)",
    )
    parser.add_argument(
        "--hotspot-delta-c", type=float, default=1.2,
        help="Simulated hotspot peak temperature elevation in Celsius (default: 1.2)",
    )
    args = parser.parse_args()
    hotspot_knee = None if args.hotspot_knee == "none" else args.hotspot_knee
    run_demo(hotspot_knee, args.hotspot_delta_c)
